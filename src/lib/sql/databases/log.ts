function riga(e: Evento, i: number): string {
  const [ora, ip, utente, esito, servizio] = e;
  const giorno = ora < "06:00:00" ? GIORNO_DOPO : GIORNO;
  return `(${i + 1},'${giorno} ${ora}','${ip}','${utente}','${esito}','${servizio}')`;
}

// Ordine cronologico, come in un vero registro.
const ordinati = [...eventi].sort((a, b) => {
  const da = (a[0] < "06:00:00" ? GIORNO_DOPO : GIORNO) + a[0];
  const db = (b[0] < "06:00:00" ? GIORNO_DOPO : GIORNO) + b[0];
  return da < db ? -1 : 1;
});

